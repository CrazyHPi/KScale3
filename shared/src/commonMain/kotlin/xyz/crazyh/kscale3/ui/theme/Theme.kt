/** 设计稿 §2.3：大卡 24，hero 28。 */
private val KScaleShapes = Shapes(
    extraSmall = RoundedCornerShape(8.dp),
    small = RoundedCornerShape(12.dp),
    medium = RoundedCornerShape(16.dp),
    large = RoundedCornerShape(24.dp),
    extraLarge = RoundedCornerShape(28.dp),
)

@Composable
fun KScaleTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val colors = if (darkTheme) DarkColors else LightColors
    val extra = if (darkTheme) DarkExtraColors else LightExtraColors
    CompositionLocalProvider(LocalKScaleExtraColors provides extra) {
        MaterialTheme(
            colorScheme = colors,
            typography = KScaleTypography,
            shapes = KScaleShapes,
            content = content,
        )
    }
}
